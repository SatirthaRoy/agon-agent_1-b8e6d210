-- Love story website schema for app endpoints

CREATE TABLE IF NOT EXISTS public.site_settings (
  id bigint PRIMARY KEY DEFAULT 1,
  partner_name text NOT NULL DEFAULT 'My Princess',
  user_name text NOT NULL DEFAULT 'Your Handsome',
  hero_title text NOT NULL DEFAULT 'To My One and Only Love',
  hero_subtitle text NOT NULL DEFAULT 'Every single second with you feels like a beautiful dream.',
  romantic_quote text DEFAULT 'You are my today and all of my tomorrows.',
  anniversary_date timestamptz NOT NULL DEFAULT now(),
  theme_id text NOT NULL DEFAULT 'lovely_pink',
  primary_color text,
  font_style text,
  secret_code text NOT NULL DEFAULT 'LOVE',
  master_pin text NOT NULL DEFAULT 'ilovesuvra',
  bg_music_url text,
  enabled_components jsonb NOT NULL DEFAULT '{
    "hero": true,
    "plushie": true,
    "countdown": true,
    "timeline": true,
    "reasons": true,
    "gallery": true,
    "notes": true,
    "bucketlist": true,
    "quiz": true,
    "lovejar": true,
    "music": true
  }'::jsonb,
  section_order jsonb NOT NULL DEFAULT '["hero","plushie","countdown","timeline","reasons","gallery","notes","bucketlist","quiz","lovejar"]'::jsonb,
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.timeline_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  event_date date NOT NULL,
  description text NOT NULL,
  location text,
  image_url text,
  order_index integer NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gallery_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  caption text,
  image_url text NOT NULL,
  date_taken date,
  is_favorite boolean NOT NULL DEFAULT false,
  order_index integer NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.love_reasons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reason text NOT NULL,
  category text NOT NULL DEFAULT 'love',
  order_index integer NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.love_notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  content text NOT NULL,
  is_secret boolean NOT NULL DEFAULT false,
  unlock_code text,
  created_at timestamptz DEFAULT now(),
  read_by_gf boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.bucket_list (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  category text NOT NULL DEFAULT 'dreams',
  completed boolean NOT NULL DEFAULT false,
  completed_date date,
  target_date date,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.quiz_questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question text NOT NULL,
  options jsonb NOT NULL,
  correct_index integer NOT NULL DEFAULT 0,
  explanation text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gf_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender text NOT NULL DEFAULT 'GF',
  message text NOT NULL,
  sentiment text NOT NULL DEFAULT 'heart',
  created_at timestamptz DEFAULT now()
);

